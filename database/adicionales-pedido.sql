-- Ejecutar en la base de datos EloteMania. También es seguro volver a
-- ejecutarlo si ya se creó la tabla adicionales en la primera versión.
-- Cada adicional puede asociarse con uno o varios productos.

CREATE TABLE IF NOT EXISTS adicionales (
  adicional_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id BIGINT NOT NULL REFERENCES productos(producto_id),
  nombre VARCHAR(100) NOT NULL,
  precio NUMERIC(12, 2) NOT NULL CHECK (precio >= 0),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT adicionales_producto_nombre_unico UNIQUE (producto_id, nombre)
);

ALTER TABLE adicionales
  DROP CONSTRAINT IF EXISTS adicionales_producto_nombre_unico;

CREATE TABLE IF NOT EXISTS adicionales_productos (
  adicional_id BIGINT NOT NULL
    REFERENCES adicionales(adicional_id) ON DELETE CASCADE,
  producto_id BIGINT NOT NULL
    REFERENCES productos(producto_id) ON DELETE CASCADE,
  PRIMARY KEY (adicional_id, producto_id)
);

CREATE INDEX IF NOT EXISTS idx_adicionales_productos_producto
  ON adicionales_productos (producto_id, adicional_id);

-- Migra las asociaciones de la primera versión de la tabla.
INSERT INTO adicionales_productos (adicional_id, producto_id)
SELECT adicional_id, producto_id
FROM adicionales
ON CONFLICT DO NOTHING;

CREATE INDEX IF NOT EXISTS idx_adicionales_activo
  ON adicionales (activo);

CREATE TABLE IF NOT EXISTS detalle_pedido_adicionales (
  detalle_pedido_adicional_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  detalle_id BIGINT NOT NULL REFERENCES detalle_pedido(detalle_id) ON DELETE CASCADE,
  adicional_id BIGINT REFERENCES adicionales(adicional_id) ON DELETE SET NULL,
  nombre_adicional VARCHAR(100) NOT NULL,
  precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  total_linea NUMERIC(12, 2) NOT NULL CHECK (total_linea >= 0)
);

CREATE INDEX IF NOT EXISTS idx_detalle_pedido_adicionales_detalle
  ON detalle_pedido_adicionales (detalle_id);

-- Guarda adicionales vendidos como líneas independientes del detalle de producto.
CREATE TABLE IF NOT EXISTS pedido_adicionales (
  pedido_adicional_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(pedido_id) ON DELETE CASCADE,
  adicional_id BIGINT REFERENCES adicionales(adicional_id) ON DELETE SET NULL,
  nombre_adicional VARCHAR(100) NOT NULL,
  precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  total_linea NUMERIC(12, 2) NOT NULL CHECK (total_linea >= 0)
);

CREATE INDEX IF NOT EXISTS idx_pedido_adicionales_pedido
  ON pedido_adicionales (pedido_id);

-- Incluye los adicionales independientes en el importe validado y cobrado.
CREATE OR REPLACE FUNCTION public.confirmar_venta(
  p_pedido_id bigint,
  p_metodo_pago_id bigint,
  p_valor_pago numeric,
  p_usuario_id bigint
)
RETURNS TABLE(
  resultado_pedido_id bigint,
  resultado_venta_id bigint,
  resultado_comprobante_id bigint,
  resultado_total numeric,
  resultado_numero_comprobante character varying
)
LANGUAGE plpgsql
AS $function$
DECLARE
  v_pedido pedidos%ROWTYPE;
  v_producto productos%ROWTYPE;
  v_venta_id BIGINT;
  v_comprobante_id BIGINT;
  v_total NUMERIC(12,2);
  v_subtotal NUMERIC(12,2);
  v_descuento NUMERIC(12,2);
  v_impuesto NUMERIC(12,2);
  v_numero_venta VARCHAR(30);
  v_numero_comprobante VARCHAR(40);
  v_detalle RECORD;
BEGIN
  SELECT *
  INTO v_pedido
  FROM pedidos
  WHERE pedido_id = p_pedido_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El pedido % no existe.', p_pedido_id;
  END IF;

  IF v_pedido.estado <> 'pendiente' THEN
    RAISE EXCEPTION
      'El pedido no se puede confirmar. Estado actual: %.',
      v_pedido.estado;
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM detalle_pedido
    WHERE pedido_id = p_pedido_id
  ) AND NOT EXISTS (
    SELECT 1
    FROM pedido_adicionales
    WHERE pedido_id = p_pedido_id
  ) THEN
    RAISE EXCEPTION 'No se puede vender un pedido vacío.';
  END IF;

  IF p_valor_pago IS NULL OR p_valor_pago <= 0 THEN
    RAISE EXCEPTION 'El valor del pago debe ser mayor que cero.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM usuarios u
    JOIN usuario_roles ur ON ur.usuario_id = u.usuario_id
    JOIN roles r ON r.rol_id = ur.rol_id
    WHERE u.usuario_id = p_usuario_id
      AND u.activo = TRUE
      AND r.nombre IN ('ADMIN', 'CAJERO')
      AND r.activo = TRUE
  ) THEN
    RAISE EXCEPTION
      'El usuario no está habilitado para registrar ventas.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM metodos_pago
    WHERE metodo_pago_id = p_metodo_pago_id
      AND activo = TRUE
  ) THEN
    RAISE EXCEPTION 'El método de pago no existe o está inactivo.';
  END IF;

  SELECT
    COALESCE(SUM(dp.cantidad * dp.precio_unitario), 0)
      + COALESCE((
          SELECT SUM(pa.total_linea)
          FROM pedido_adicionales pa
          WHERE pa.pedido_id = p_pedido_id
        ), 0),
    COALESCE(SUM(dp.descuento), 0),
    COALESCE(SUM(dp.impuesto), 0),
    COALESCE(SUM(dp.total_linea), 0)
      + COALESCE((
          SELECT SUM(pa.total_linea)
          FROM pedido_adicionales pa
          WHERE pa.pedido_id = p_pedido_id
        ), 0)
  INTO v_subtotal, v_descuento, v_impuesto, v_total
  FROM detalle_pedido dp
  WHERE dp.pedido_id = p_pedido_id;

  IF v_total <= 0 THEN
    RAISE EXCEPTION 'El total de la venta debe ser mayor que cero.';
  END IF;

  IF v_descuento > v_subtotal THEN
    RAISE EXCEPTION 'El descuento supera el subtotal.';
  END IF;

  IF ROUND(v_subtotal - v_descuento + v_impuesto, 2)
     <> ROUND(v_total, 2) THEN
    RAISE EXCEPTION
      'Los totales de los detalles no coinciden. Revise los importes.';
  END IF;

  IF ROUND(p_valor_pago, 2) <> ROUND(v_total, 2) THEN
    RAISE EXCEPTION
      'El pago (%) debe coincidir con el total (%).',
      p_valor_pago, v_total;
  END IF;

  FOR v_detalle IN
    SELECT DISTINCT dp.producto_id
    FROM detalle_pedido dp
    WHERE dp.pedido_id = p_pedido_id
      AND dp.producto_id IS NOT NULL
    ORDER BY dp.producto_id
  LOOP
    SELECT *
    INTO v_producto
    FROM productos
    WHERE producto_id = v_detalle.producto_id
    FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION
        'Uno de los productos del pedido ya no existe.';
    END IF;

    IF v_producto.eliminado_en IS NOT NULL
       OR NOT v_producto.disponible THEN
      RAISE EXCEPTION
        'El producto "%" no está disponible.',
        v_producto.nombre;
    END IF;
  END LOOP;

  FOR v_detalle IN
    SELECT
      dp.producto_id,
      SUM(dp.cantidad) AS cantidad_total
    FROM detalle_pedido dp
    WHERE dp.pedido_id = p_pedido_id
      AND dp.producto_id IS NOT NULL
    GROUP BY dp.producto_id
    ORDER BY dp.producto_id
  LOOP
    SELECT *
    INTO v_producto
    FROM productos
    WHERE producto_id = v_detalle.producto_id;

    IF v_producto.controla_inventario THEN
      IF v_producto.stock_actual < v_detalle.cantidad_total THEN
        RAISE EXCEPTION
          'Stock insuficiente para "%". Disponible: %, solicitado: %.',
          v_producto.nombre,
          v_producto.stock_actual,
          v_detalle.cantidad_total;
      END IF;

      UPDATE productos
      SET stock_actual = stock_actual - v_detalle.cantidad_total
      WHERE producto_id = v_detalle.producto_id;

      INSERT INTO movimientos_inventario (
        producto_id,
        usuario_id,
        pedido_id,
        tipo,
        cantidad,
        stock_anterior,
        stock_nuevo,
        motivo
      )
      VALUES (
        v_producto.producto_id,
        p_usuario_id,
        p_pedido_id,
        'salida',
        v_detalle.cantidad_total,
        v_producto.stock_actual,
        v_producto.stock_actual - v_detalle.cantidad_total,
        'Venta confirmada'
      );
    END IF;
  END LOOP;

  v_numero_venta :=
    'V-' || TO_CHAR(CURRENT_TIMESTAMP, 'YYYYMMDDHH24MISS')
    || '-' || p_pedido_id;

  INSERT INTO ventas (
    pedido_id,
    numero_venta,
    cajero_id,
    subtotal,
    descuento,
    impuesto,
    total,
    estado
  )
  VALUES (
    p_pedido_id,
    v_numero_venta,
    p_usuario_id,
    v_subtotal,
    v_descuento,
    v_impuesto,
    v_total,
    'vigente'
  )
  RETURNING venta_id INTO v_venta_id;

  INSERT INTO pagos (
    pedido_id,
    metodo_pago_id,
    registrado_por,
    valor,
    estado
  )
  VALUES (
    p_pedido_id,
    p_metodo_pago_id,
    p_usuario_id,
    v_total,
    'confirmado'
  );

  v_numero_comprobante :=
    'B-' || TO_CHAR(CURRENT_TIMESTAMP, 'YYYYMMDDHH24MISS')
    || '-' || p_pedido_id;

  INSERT INTO comprobantes (
    pedido_id,
    venta_id,
    numero_comprobante
  )
  VALUES (
    p_pedido_id,
    v_venta_id,
    v_numero_comprobante
  )
  RETURNING comprobante_id INTO v_comprobante_id;

  UPDATE pedidos
  SET estado = 'completado',
      subtotal = v_subtotal,
      descuento = v_descuento,
      impuesto = v_impuesto,
      total = v_total,
      completado_en = CURRENT_TIMESTAMP
  WHERE pedido_id = p_pedido_id;

  INSERT INTO auditoria (
    usuario_id,
    accion,
    tabla_afectada,
    registro_id,
    descripcion
  )
  VALUES (
    p_usuario_id,
    'CONFIRMAR_VENTA',
    'pedidos',
    p_pedido_id,
    'Venta ' || v_numero_venta
      || ' confirmada por valor de ' || v_total
  );

  RETURN QUERY
  SELECT
    p_pedido_id,
    v_venta_id,
    v_comprobante_id,
    v_total,
    v_numero_comprobante;
END;
$function$;

